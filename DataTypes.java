class DataTypes
{
	public static void main(String args[])
	{
		int age = 20;
		double percentage = 85.75;
		char grade = 'A';
		boolean pass = true;

		System.out.println("Age = "+age);
		System.out.println("Percentage = "+percentage);
		System.out.println("Grade = "+grade);
		System.out.println("Pass = "+pass);
	}	
}